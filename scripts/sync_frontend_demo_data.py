"""
Synchronizes verified POIs and trained Q1 ML benchmark results directly into
frontend/src/data/demoCatalog.js so the static Vercel deployment boots cleanly in
0ms with complete domain fidelity whenever no remote AI server is attached.
"""

import json
import os
import sys

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BACKEND_DIR = os.path.join(ROOT_DIR, "backend")
sys.path.insert(0, ROOT_DIR)
sys.path.insert(0, BACKEND_DIR)

from app.main import load_spots, METRICS_PATH
from backend.ml.backbone import SWIPE_CARDS_CATALOG


def main():
    spots = load_spots()
    cities = sorted({s["city"] for s in spots if s.get("city")})

    metrics = {}
    if os.path.exists(METRICS_PATH):
        with open(METRICS_PATH, "r", encoding="utf-8") as f:
            metrics = json.load(f)

    out_path = os.path.join(ROOT_DIR, "frontend", "src", "data", "demoCatalog.js")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)

    payload = (
        "// Auto-generated by scripts/sync_frontend_demo_data.py — DO NOT EDIT MANUALLY\n"
        f"export const DEMO_DESTINATIONS = {json.dumps(cities, ensure_ascii=False, indent=2)};\n\n"
        f"export const DEMO_SPOTS = {json.dumps(spots, ensure_ascii=False, indent=2)};\n\n"
        f"export const DEMO_SWIPE_CARDS = {json.dumps(SWIPE_CARDS_CATALOG, ensure_ascii=False, indent=2)};\n\n"
        f"export const DEMO_ML_METRICS = {json.dumps(metrics, ensure_ascii=False, indent=2)};\n"
    )
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(payload)

    print(
        f"[Sync] Wrote {len(spots)} spots across {len(cities)} cities + Q1 metrics -> {out_path}"
    )


if __name__ == "__main__":
    main()
